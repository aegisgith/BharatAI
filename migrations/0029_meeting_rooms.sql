-- Migration 0029: private boardrooms -- inventory and bookings.
--
-- The homepage has advertised four WTC Mumbai boardrooms since launch under the
-- promise "Rooms are subject to availability on 20-21 November 2026", and nothing
-- anywhere tracks that availability. The public CTA deliberately routes an enquiry
-- to the contact form -- rooms are charged by the hour plus GST, so the price has
-- to be quoted, not self-served -- but the team still has to answer "is Jasmine
-- free at 11 on the 20th?" and today the only answer is somebody's memory. This is
-- the ledger behind that promise, not a shop front.
--
-- WHY BOOKINGS-AS-ROWS AND NOT A PRE-GENERATED SLOT GRID
--   The rooms are priced PER HOUR, so the hour is already the commercial atom.
--   Fixing the booking atom at one hour is what makes UNIQUE(room_id, slot_start)
--   a real guarantee: SQLite has no exclusion constraint, so overlap between
--   variable-length bookings cannot be enforced declaratively at all. A two-hour
--   reservation is therefore two rows sharing a group_ref, not one row with a
--   duration. A pre-generated grid (4 rooms x 2 days x 9 hours = 72 rows) would
--   have to be regenerated by hand -- another --remote execute -- every time the
--   hours change, and it cannot keep a cancellation for audit while also freeing
--   the hour. The partial index below does both.
--
-- Room data below is copied verbatim from public/index.html (card text + image alt
-- attributes). Nothing here is invented. Note that Board Room 4 seats 12 yet is
-- priced above Board Room 3 which seats 20 -- that is what the site publishes.
--
-- No FOREIGN KEY clauses, following 0021/0027/0028: a FK on attendee_id would make
-- the existing DELETE FROM attendees in the admin panel start failing.

CREATE TABLE IF NOT EXISTS meeting_rooms (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  event_id   INTEGER NOT NULL DEFAULT 1,
  slug       TEXT    NOT NULL UNIQUE,   -- stable key, independent of the row id
  label      TEXT    NOT NULL,          -- what the site calls it
  wtc_name   TEXT    NOT NULL,          -- what the venue calls it, for signage and the WTC
  layout     TEXT,                      -- NULL where the site does not state one
  capacity   INTEGER NOT NULL,
  price_inr  INTEGER NOT NULL,          -- per hour, exclusive of GST
  image_url  TEXT,
  sort_order INTEGER NOT NULL DEFAULT 0,
  is_active  INTEGER NOT NULL DEFAULT 1,
  created_at TEXT    DEFAULT CURRENT_TIMESTAMP
);

