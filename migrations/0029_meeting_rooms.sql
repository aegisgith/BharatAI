-- One row per room-hour. slot_start is always 'YYYY-MM-DD HH:00' -- the same
-- 'YYYY-MM-DD HH:MM' text shape sessions.start_time uses, so the two sort and
-- compare together without conversion.
CREATE TABLE IF NOT EXISTS room_bookings (
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  event_id      INTEGER NOT NULL DEFAULT 1,
  room_id       INTEGER NOT NULL,
  slot_date     TEXT    NOT NULL,               -- 'YYYY-MM-DD', denormalised for the day grid
  slot_start    TEXT    NOT NULL,               -- 'YYYY-MM-DD HH:00'
  slot_end      TEXT    NOT NULL,               -- 'YYYY-MM-DD HH:00', always +1h
  group_ref     TEXT,                           -- ties the consecutive hours of one reservation
  kind          TEXT    NOT NULL DEFAULT 'booking',  -- booking | block
  attendee_id   INTEGER,                        -- NULL for an admin-created block
  meeting_id    INTEGER,                        -- set when the hour was booked from a meeting request
  title         TEXT,
  headcount     INTEGER,
  notes         TEXT,
  contact_name  TEXT,
  contact_email TEXT,
  contact_phone TEXT,
  price_inr     INTEGER NOT NULL DEFAULT 0,     -- snapshot of the rate at booking time
  status        TEXT    NOT NULL DEFAULT 'held',    -- held | confirmed | cancelled | rejected
  created_by    TEXT,
  created_at    TEXT    DEFAULT CURRENT_TIMESTAMP,
  updated_at    TEXT    DEFAULT CURRENT_TIMESTAMP,
  cancelled_at  TEXT
);

-- THE GUARANTEE. Two people cannot hold the same room-hour, whatever the API does
-- or fails to do. Partial, so a cancelled or rejected row keeps its history while
-- releasing the hour -- which a booking_id column on a pre-generated grid cannot.
CREATE UNIQUE INDEX IF NOT EXISTS ux_room_bookings_slot
  ON room_bookings(room_id, slot_start)
  WHERE status IN ('held', 'confirmed');

CREATE INDEX IF NOT EXISTS idx_room_bookings_day      ON room_bookings(slot_date, room_id, slot_start);
CREATE INDEX IF NOT EXISTS idx_room_bookings_attendee ON room_bookings(attendee_id, slot_start);
CREATE INDEX IF NOT EXISTS idx_room_bookings_group    ON room_bookings(group_ref);
CREATE INDEX IF NOT EXISTS idx_room_bookings_meeting  ON room_bookings(meeting_id);
