// Self-host the Google Fonts the site and the app use.
//
// Why: every page used to load them from fonts.googleapis.com + fonts.gstatic.com,
// two extra servers to connect to before any text could render in the right
// face. On a phone on a slow connection that was the better part of a second.
// Served from our own origin they ride the connection the page already has, and
// the service worker can keep them for the venue.
//
// What it writes: public/fonts/<family>-<subset>-<weight>.woff2 (one file per
// @font-face block Google serves) and two stylesheets, Google's own CSS with the
// URLs pointed at /fonts/: public/css/fonts.css for the marketing site (Manrope
// and Mukta, exactly what those pages loaded from Google before, so that
// style.css rules naming Montserrat keep falling back to Arial as they always
// did) and public/css/fonts-app.css for the pages the worker renders (/app,
// /admin, /register and the rest), with every family their @import named. The
// unicode-range subsets are kept, so a page still downloads only the scripts it
// shows (Mukta's Devanagari file only where there is Hindi on the page).
//
// Run again only to add a family or a weight: edit FAMILIES, run, then bump the
// ?v= on every "/css/fonts.css?v=" and "/css/fonts-app.css?v=" reference
// (public/*.html, src/index.tsx) and the entries in public/sw.js. Licence: all
// five are OFL.
//
//   node scripts/fetch-fonts.mjs
import { mkdirSync, writeFileSync } from 'node:fs'

const FAMILIES = [
  'Bricolage+Grotesque:opsz,wght@12..96,400..800',
  'Manrope:wght@300..800',
  'Montserrat:wght@600;700;800',
  'Playfair+Display:wght@600;700',
  'Mukta:wght@500;600;700',
]
const SITE_FAMILIES = ['Manrope', 'Mukta']
const CSS_URL = 'https://fonts.googleapis.com/css2?' + FAMILIES.map((f) => 'family=' + f).join('&') + '&display=swap'
// A current Chrome: Google answers woff2 with unicode-range subsets only to a
// browser it knows supports them.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/128.0.0.0 Safari/537.36'

const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': UA } })).text()
const blocks = [...css.matchAll(/\/\* (\S+) \*\/\s*@font-face \{([\s\S]*?)\}/g)]
if (!blocks.length) throw new Error('Google answered no @font-face blocks:\n' + css.slice(0, 300))

mkdirSync('public/fonts', { recursive: true })
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-')
const HEAD = '/* Generated by scripts/fetch-fonts.mjs - do not edit by hand. Google Fonts, served from this origin. */\n'
let site = HEAD, all = HEAD
let files = 0
for (const [, subset, body] of blocks) {
  const family = /font-family: '([^']+)'/.exec(body)[1]
  const weight = /font-weight: ([^;]+)/.exec(body)[1].trim().replace(/\s+/g, '-')
  const url = /url\(([^)]+)\)/.exec(body)[1]
  const name = `${slug(family)}-${subset}-${weight}.woff2`
  const res = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!res.ok) throw new Error(`${name}: ${res.status} from ${url}`)
  writeFileSync('public/fonts/' + name, Buffer.from(await res.arrayBuffer()))
  files++
  const block = `/* ${subset} */\n@font-face {${body.replace(url, '/fonts/' + name)}}\n`
  all += block
  if (SITE_FAMILIES.includes(family)) site += block
}
writeFileSync('public/css/fonts.css', site)
writeFileSync('public/css/fonts-app.css', all)
console.log(`[fetch-fonts] ${files} files in public/fonts; fonts.css ${site.length} bytes (${SITE_FAMILIES.join(', ')}), fonts-app.css ${all.length} bytes`)
