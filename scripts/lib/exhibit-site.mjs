// The wall's block in a page, LF text in and out: the block starts with its own
// start line (WALL_START), which replaces the old one.
export function fillWall(src, html) {
  const a = src.indexOf('<!-- exhibitors:start'), b = src.indexOf('<!-- exhibitors:end -->')
  if (a < 0 || b < 0 || b < a) throw new Error('exhibitors markers missing')
  const lineStart = src.lastIndexOf('\n', a) + 1
  const ind = src.slice(lineStart, a)
  const body = html.split('\n').map((l) => (l ? ind + l : l)).join('\n')
  return src.slice(0, lineStart) + body + ind + src.slice(b)
}

// ==================== the Innovation Talk cards ====================

const nm = (s) => String(s || '').toLowerCase().replace(/^(dr\.?|mr\.?|ms\.?|mrs\.?|shri\.?|smt\.?)\s+/, '').replace(/[^a-z0-9]+/g, ' ').trim()
const initials = (name) => name.replace(/^(Dr\.?|Mr\.?|Ms\.?)\s+/, '').split(/\s+/).filter(Boolean).slice(0, 2).map((w) => w[0].toUpperCase()).join('')

// The app's talks (the programme's `talks`), with what only the JSON list
// (scripts/data/innovation-talks.json) holds: the slug of a baked photo, the logo
// file, the government order, a topic the app lacks. The app's words and photo win.
export function talksFromApp(appTalks, listed) {
  const byName = new Map(listed.map((t) => [nm(t.name), t]))
  return appTalks.filter((a) => String(a.speaker_name || '').trim()).map((a) => {
    const j = byName.get(nm(a.speaker_name)) || null
    return {
      name: String(a.speaker_name).trim(), title: a.speaker_title || j?.title || '', company: a.company || j?.company || '',
      topic: a.topic || j?.topic || '', slug: j?.slug || slugOf(a.speaker_name), logoFile: j?.logoFile, government: j?.government,
      photoSrc: String(a.photo_url || '').replace(/^\//, ''),
    }
  })
}

// The files a talk's company logo may be, best first: the JSON's own logo file (a
// government department), then the exhibitor wall's file for that company.
export function talkLogoFiles(t, looks = []) {
  const look = looks.find((e) => same(key(e.name), key(t.company)))
  return [t.logoFile, `images/exhibitors/${slugOf(t.company)}.webp`, look ? `images/exhibitors/${look.slug || slugOf(look.name)}.webp` : '', `images/exhibitors/${slugOf(tidy(t.company))}.webp`].filter(Boolean)
}

// Each card carries the company's logo, sized as the wall sizes them, a wide wordmark
// lower than a square mark, so they read at the same weight. `logo` is { file, w, h }.
export function sizeTalkLogo(t, logo) {
  if (!logo || !logo.w || !logo.h) { delete t.logo; return t }
  const r = logo.w / logo.h
  let h = Math.min(34, Math.max(18, 30 * Math.pow(r, -0.4)))
  if (h * r > 120) h = 120 / r
  if (t.government) h = Math.min(44, 170 / r)
  t.logo = { file: logo.file, w: logo.w, h: logo.h, dh: Math.round(h) }
  return t
}

// The three blocks: /exhibition's speaker wall, /conference's cards (government first)
// and llms.txt. Each talk: name, title, company, topic, government, photoSrc (a site
// path without the leading slash, or an https address; '' for initials) and logo.
export function renderTalks(talks) {
  const logo = (t, margin) => t.logo
    ? `<img width="${t.logo.w}" height="${t.logo.h}" loading="lazy" decoding="async" src="${esc(t.logo.file)}" alt="" class="talk-logo" style="display:block;height:${t.logo.dh}px;width:auto;max-width:${t.government ? 170 : 120}px;margin:${margin};position:relative;z-index:1;">\n    `
    : ''
  const cards = talks.map((t) => {
    const alt = `${t.name}, ${t.title ? t.title + ', ' : ''}${t.company}`
    const photo = t.photoSrc
      ? `<img width="320" height="320" loading="lazy" decoding="async" src="${esc(t.photoSrc)}" alt="${esc(alt)}" class="speaker-photo" style="aspect-ratio:1;border-radius:50%;width:120px;height:120px;margin:0 auto;object-fit:cover;">`
      : `<div class="speaker-photo" aria-hidden="true" style="width:120px;height:120px;margin:0 auto;border-radius:50%;display:flex;align-items:center;justify-content:center;background:linear-gradient(135deg,rgba(255,107,0,0.14),rgba(57,73,171,0.14));color:var(--indigo-light);font-family:var(--font-display);font-weight:800;font-size:2rem;">${esc(initials(t.name))}</div>`
    const topic = t.topic
      ? `<p class="talk-topic" style="font-size:0.84rem;color:var(--charcoal);line-height:1.45;margin:0.6rem 0 0;">&ldquo;${esc(t.topic)}&rdquo;</p>`
      : `<p class="talk-topic" style="font-size:0.8rem;color:var(--dark-grey);margin:0.6rem 0 0;">Topic to be announced</p>`
    return `<div class="speaker-card reveal" style="text-align:center;align-items:center;">
    ${photo}
    <h4>${esc(t.name)}</h4>
    ${t.title ? `<p style="font-size:0.8rem;color:var(--saffron);font-weight:600;margin:0;">${esc(t.title)}</p>` : ''}
    ${logo(t, '0 auto')}<p class="spk-org" style="font-size:0.78rem;">${esc(t.company)}</p>
    ${topic}
</div>`
  })
  const exhibition = `<div class="speakers-grid">\n${cards.join('\n')}\n</div>\n`

  // A talk with "government" in the JSON stands in a row of its own at the top, in that
  // order; the list's own order stays otherwise.
  const confCard = (t) => {
    const alt = `${t.name}, ${t.title ? t.title + ', ' : ''}${t.company}`
    const avatar = t.photoSrc
      ? `<div class="speaker-avatar"><img width="320" height="320" loading="lazy" decoding="async" src="${esc(t.photoSrc)}" alt="${esc(alt)}"></div>`
      : `<div class="speaker-avatar" aria-hidden="true"><span style="color:#fff;font-family:var(--font-display);font-weight:800;font-size:1.4rem;letter-spacing:0.02em;">${esc(initials(t.name))}</span></div>`
    const topic = t.topic
      ? `<p class="talk-topic" style="font-size:0.84rem;color:var(--charcoal);line-height:1.45;margin:0.6rem 0 0;position:relative;z-index:1;">&ldquo;${esc(t.topic)}&rdquo;</p>`
      : `<p class="talk-topic" style="font-size:0.8rem;color:var(--dark-grey);margin:0.6rem 0 0;position:relative;z-index:1;">Topic to be announced</p>`
    return `<div class="speaker-card reveal">
    ${avatar}
    <h4>${esc(t.name)}</h4>
    ${t.title ? `<div class="speaker-role">${esc(t.title)}</div>` : ''}
    ${logo(t, '0.6rem auto 0.3rem')}<div class="speaker-org">${esc(t.company)}</div>
    ${topic}
</div>`
  }
  const govTalks = talks.filter((t) => t.government).sort((a, b) => a.government - b.government)
  const groupHead = (words) => `<h3 class="reveal" style="margin:0 0 1.25rem;text-align:center;font-family:var(--font-display);font-weight:800;font-size:1.35rem;color:var(--charcoal);">${words}</h3>`
  const conference = [
    groupHead('Government'),
    `<div class="speakers-grid gov-talks" style="margin-bottom:3rem;">\n${govTalks.map(confCard).join('\n')}\n</div>`,
    groupHead('Exhibitors'),
    `<div class="speakers-grid">\n${talks.filter((t) => !t.government).map(confCard).join('\n')}\n</div>\n`,
  ].join('\n')

  const lines = talks.map((t) => `- **${t.name}** (${t.title ? t.title + ', ' : ''}${t.company})${t.topic ? ' — ' + t.topic : ''}`)
  const llms = [
    '## Innovation Talk & Showcase speakers',
    '',
    `${talks.length} stage talks by exhibitors and government departments at Bharat AI Innovation 2026, 20–21 November, WTC Mumbai (hall and times to be announced):`,
    ...lines,
    '',
  ].join('\n') + '\n'
  return { exhibition, conference, llms }
}

// The talks' block in a page, LF text in and out, keeping its start line.
export function fillTalks(src, body) {
  const a = src.indexOf('<!-- talks:start'), b = src.indexOf('<!-- talks:end -->')
  if (a < 0 || b < 0 || b < a) throw new Error('talks markers missing')
  const lineStart = src.lastIndexOf('\n', a) + 1
  const ind = src.slice(lineStart, a)
  const startLine = src.slice(a, src.indexOf('\n', a) + 1)
  const indented = body.split('\n').map((l) => (l ? ind + l : l)).join('\n')
  return src.slice(0, lineStart) + ind + startLine + indented + ind + src.slice(b)
}

// ==================== an image's size from its first bytes ====================

// PNG, JPEG or WebP: { w, h }, or null. For an upload the build has not baked yet,
// read from the start of the file (the Worker reads 64 KB of it from the bucket).
export function imageSize(bytes) {
  const b = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes || [])
  const u16 = (i) => (b[i] << 8) | b[i + 1]
  const u32 = (i) => ((b[i] << 24) >>> 0) + (b[i + 1] << 16) + (b[i + 2] << 8) + b[i + 3]
  if (b.length >= 24 && b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47) return { w: u32(16), h: u32(20) }
  if (b.length >= 4 && b[0] === 0xff && b[1] === 0xd8) {
    let i = 2
    while (i + 9 < b.length) {
      if (b[i] !== 0xff) { i++; continue }
      const m = b[i + 1]
      if (m === 0xd8 || m === 0x01 || (m >= 0xd0 && m <= 0xd7) || m === 0xff) { i += m === 0xff ? 1 : 2; continue }
      if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) return { w: u16(i + 7), h: u16(i + 5) }
      i += 2 + u16(i + 2)
    }
    return null
  }
  const tag = (i, s) => String.fromCharCode(b[i], b[i + 1], b[i + 2], b[i + 3]) === s
  if (b.length >= 30 && tag(0, 'RIFF') && tag(8, 'WEBP')) {
    if (tag(12, 'VP8 ')) return { w: ((b[27] << 8) | b[26]) & 0x3fff, h: ((b[29] << 8) | b[28]) & 0x3fff }
    if (tag(12, 'VP8L')) { const v = b[21] | (b[22] << 8) | (b[23] << 16) | (b[24] << 24); return { w: (v & 0x3fff) + 1, h: ((v >> 14) & 0x3fff) + 1 } }
    if (tag(12, 'VP8X')) return { w: 1 + (b[24] | (b[25] << 8) | (b[26] << 16)), h: 1 + (b[27] | (b[28] << 8) | (b[29] << 16)) }
  }
  return null
}
