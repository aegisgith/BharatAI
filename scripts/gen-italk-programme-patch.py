# The Innovation Talks in the app's programme, brought to the agenda WITHOUT replacing it
# (14 Nov 2026). scripts/sql/schedule.sql replaces every session for event 1, which now
# loses what Admin -> Conference keeps against a session's id (speaker links, owners,
# drafts, announcements, live questions). This writes a patch for the Innovation Talk
# sessions only ("Innovation Talk: <company>"), read against production:
#   - a talk session already there keeps its id: only its hall and times change;
#   - a talk the agenda has and production does not is added, as schedule.sql words it;
#   - a talk production has and the agenda no longer does is made a draft (hidden from
#     attendees, kept, one untick in Admin brings it back), never deleted;
#   - a company with two slots (Kirusa, Image Infosystems, Dysosphere, Info Science
#     Labs) keeps its session in the first and gets a second one.
# The talks list (innovation_talks) gets its times from scripts/sql/innovation-talk-times.sql
# (scripts/gen-talk-times.mjs); the few it cannot match are set at the end of this patch.
#
#   npx wrangler d1 execute bharatai-production --remote --json --command "<the SELECT below>" > prod-sessions.json
#   python -I scripts/gen-italk-programme-patch.py prod-sessions.json > scripts/sql/italk-programme-2026-11-14.sql
import json, re, sys

PREFIX = 'Innovation Talk:'
prod = json.load(open(sys.argv[1], encoding='utf-8'))[0]['results']
sql = open('scripts/sql/schedule.sql', encoding='utf-8').read()

COLS = ['title', 'description', 'speaker_name', 'speaker_title', 'speaker_avatar', 'session_type', 'track', 'room', 'start_time', 'end_time', 'capacity']
rows = []
for m in re.finditer(r"^\(1, (.*)\),?;?$", sql, re.M):
    vals = re.findall(r"'((?:[^']|'')*)'|(NULL)|(\d+)", m.group(1))
    v = [(None if b else (int(c) if c else a.replace("''", "'"))) for a, b, c in vals]
    if len(v) == len(COLS): rows.append(dict(zip(COLS, v)))
want = sorted([r for r in rows if str(r['title']).startswith(PREFIX)], key=lambda r: (r['start_time'], r['room']))
have = [p for p in prod if str(p['title']).startswith(PREFIX)]

q = lambda v: 'NULL' if v is None else (str(v) if isinstance(v, int) else "'" + str(v).replace("'", "''") + "'")
out = ['-- Generated by scripts/gen-italk-programme-patch.py on 14 Nov 2026; see that file. Safe to run once.',
       '-- Innovation Talk sessions only: times and halls changed by id, missing ones added, dropped ones made drafts.']
used = set()
moved = added = 0
for w in want:
    same = [p for p in have if p['title'] == w['title'] and p['id'] not in used]
    same.sort(key=lambda p: p['start_time'] or '')
    if same:
        p = same[0]; used.add(p['id'])
        if (p['room'], p['start_time'], p['end_time']) != (w['room'], w['start_time'], w['end_time']):
            out.append(f"-- {w['title']}: {p['room']} {p['start_time']}-{(p['end_time'] or '')[11:]} -> {w['room']} {w['start_time']}-{w['end_time'][11:]}")
            out.append(f"UPDATE sessions SET room = {q(w['room'])}, start_time = {q(w['start_time'])}, end_time = {q(w['end_time'])} WHERE id = {p['id']} AND event_id = 1;")
            moved += 1
    else:
        out.append(f"-- add {w['title']} ({w['room']}, {w['start_time']}-{w['end_time'][11:]})")
        out.append('INSERT INTO sessions (event_id, ' + ', '.join(COLS) + ') VALUES (1, ' + ', '.join(q(w[k]) for k in COLS) + ');')
        added += 1
dropped = [p for p in have if p['id'] not in used]
for p in dropped:
    out.append(f"-- {p['title']} ({p['start_time']}) is no longer on the agenda: a draft, hidden from attendees, kept")
    out.append(f"INSERT INTO session_admin (session_id, status, note, updated_at) VALUES ({p['id']}, 'draft', 'Not on the 13 Nov agenda sheet (14 Nov 2026)', CURRENT_TIMESTAMP) ON CONFLICT(session_id) DO UPDATE SET status = 'draft', note = excluded.note, updated_at = CURRENT_TIMESTAMP;")
sys.stderr.write(f'{len(want)} talk sessions on the agenda, {len(have)} in production: {moved} moved, {added} added, {len(dropped)} made drafts ({", ".join(p["title"] for p in dropped)})\n')
sys.stdout.reconfigure(encoding='utf-8', newline='\n')
print('\n'.join(out))
